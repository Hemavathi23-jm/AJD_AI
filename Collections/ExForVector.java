import java.util.*;

public class ExForVector {
    public static void main(String[] args) {
        Vector<String> v = new Vector<String>();
        v.add("A");
        v.add("B");
        v.add("C");
        for(String str: v) {
            System.out.println(str);
        }
        Vector<Integer> v1 = new Vector<Integer>();
            v1.add(10);
            v1.add(20);
            v1.add(30);
            for(Integer num: v1) {
                System.out.println(num);
            }
        }
    }
    

